    public static let supportedLocales: [String] = [
        "en", "ko", "ja", "zh-Hans", "zh-Hant", "de", "fr", "pt", "ru", "tr", "vi",
    ]

    public static func canonicalCode(for locale: Locale = .autoupdatingCurrent) -> String {
        let id = locale.identifier.lowercased().replacingOccurrences(of: "_", with: "-")
        if id.hasPrefix("zh-hant") || id.hasPrefix("zh-tw") || id.hasPrefix("zh-hk") || id.hasPrefix("zh-mo") {
            return "zh-Hant"
        }
        if id.hasPrefix("zh") {
            return "zh-Hans"
        }
        for prefix in ["ko", "ja", "de", "fr", "pt", "ru", "tr", "vi"] {
            if id == prefix || id.hasPrefix("\(prefix)-") {
                return prefix
            }
        }
        return "en"
    }

    public static func text(_ key: String, locale: Locale = .autoupdatingCurrent) -> String {
        let code = canonicalCode(for: locale)
        if let bundleValue = lookupBundleString(key: key, language: code) {
            return bundleValue
        }
        if let table = embeddedTables[code]?[key] {
            return table
        }
        return embeddedTables["en"]?[key] ?? key
    }

    public static func formatted(_ key: String, _ arg: String, locale: Locale = .autoupdatingCurrent) -> String {
        String(format: text(key, locale: locale), arg)
    }

    private static func lookupBundleString(key: String, language: String) -> String? {
        for bundle in resourceBundles {
            if let path = bundle.path(forResource: "Localizable", ofType: "strings", inDirectory: nil, forLocalization: language),
               let dict = NSDictionary(contentsOfFile: path) as? [String: String],
               let value = dict[key],
               !value.isEmpty {
                return value
            }
        }
        return nil
    }

    private static var resourceBundles: [Bundle] {
        var bundles: [Bundle] = []
        #if SWIFT_PACKAGE
        bundles.append(Bundle.module)
        #endif
        bundles.append(Bundle.main)
        return bundles
    }

